/**
 * Normalize residence to ISO code.
 * @param {string|null|undefined} str
 * @returns {string|null}
 */
export function parseResidence(str) {
  if (!str || typeof str !== "string") return null;
  // NFKC folds full-width Latin ("ＵＳＡ") and the ideographic space
  const trimmed = str.normalize("NFKC").trim();
  const lower = trimmed.toLowerCase();
  if (trimmed === "" || NON_VALUES.has(lower)) return null;
  // Skip values that look like time data (column shift artifacts)
  if (/^\d+:\d+:\d+$/.test(trimmed)) return null;
  // Skip gender values leaked into residence column
  if (trimmed === "男" || trimmed === "女") return null;
  // Skip organization names
  if (trimmed.startsWith("学連")) return null;
  if (SCHOOL.test(trimmed)) return null;

  // Country (case-insensitive; toLowerCase is no-op on CJK, so Japanese keys also match)
  if (COUNTRIES[lower]) return COUNTRIES[lower];

  // ISO 3166-1 alpha-2 passthrough (e.g. "US", "no", "JP")
  if (/^[a-zA-Z]{2}$/.test(trimmed)) return trimmed.toUpperCase();

  // ISO 3166-1 alpha-3 → alpha-2 conversion, whatever the case ("aus", "Jpn")
  if (/^[a-zA-Z]{3}$/.test(trimmed)) {
    const code = ISO3_TO_ISO2[trimmed.toUpperCase()];
    if (code) return code;
  }

  // Japanese prefecture, with or without its 都/府/県 suffix
  if (PREFECTURES[trimmed]) return PREFECTURES[trimmed];
  if (BARE_PREFECTURES[trimmed]) return BARE_PREFECTURES[trimmed];

  // Municipality → prefecture
  if (MUNICIPALITIES[trimmed]) return MUNICIPALITIES[trimmed];

  // Prefecture followed by anything: an address ("神奈川県横浜市") or the JTU
  // 登録地, which names the prefecture's federation ("東京都トライアスロン連合")
  for (const [name, code] of PREFECTURE_PREFIXES) {
    if (trimmed.startsWith(name)) return code;
  }

  // A trailing parenthetical qualifier ("GBR (Great Britain)", "東京(神奈川)")
  const unqualified = trimmed.match(/^(.+?)\s*\([^)]*\)$/);
  if (unqualified) return parseResidence(unqualified[1]);

  // Municipality followed by a neighbourhood ("金沢市新保")
  for (
    let length = Math.min(MAX_MUNICIPALITY_LENGTH, trimmed.length - 1);
    length >= 2;
    length--
  ) {
    const code = MUNICIPALITIES[trimmed.slice(0, length)];
    if (code) return code;
  }

  return null;
}
